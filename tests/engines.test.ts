test('Godot Linux non-embedded export attests the fresh .pck sidecar, embedded does not', async (t) => {
  const root = await tempDir(t, 'appops-godot-pck-');
  await provisionTools(t, root);
  const godot = join(root, 'godot');
  await write(godot, 'project.godot', godotProject);
  // Default Godot 4 Linux preset: no embed_pck -> data ships as a .pck sidecar.
  await write(godot, 'export_presets.cfg', `[preset.0]
name="Linux"
platform="Linux/X11"
runnable=true
export_path="game.x86_64"
[preset.0.options]
binary_format/embed_pck=false
`);
  const plan = await createBuildPlan(await inspectProject(godot), { target: 'linux', outputPath: join(root, 'out') });
  assert.equal(plan.commands.length, 1);
  assert.equal(plan.expectedArtifacts.length, 2, 'executable + .pck must both be expected');
  assert.ok(plan.expectedArtifacts.some((a) => a.endsWith('.pck')), 'fresh .pck must be attested');

  const embedded = join(root, 'godot-embed');
  await write(embedded, 'project.godot', godotProject);
  await write(embedded, 'export_presets.cfg', `[preset.0]
name="Linux"
platform="Linux/X11"
runnable=true
export_path="game.x86_64"
[preset.0.options]
binary_format/embed_pck=true
`);
  const embeddedPlan = await createBuildPlan(await inspectProject(embedded), { target: 'linux', outputPath: join(root, 'out2') });
  assert.equal(embeddedPlan.expectedArtifacts.length, 1, 'embedded pck has no sidecar to attest');
  assert.ok(!embeddedPlan.expectedArtifacts.some((a) => a.endsWith('.pck')));
});

