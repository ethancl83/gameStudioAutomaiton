test('scanToolchains lists official tools and does not fake availability', async () => {
  const tools = await scanToolchains();
  const names = tools.map((t) => t.name);
  for (const required of ['godot', 'unity', 'unreal-uat', 'java', 'android-sdk', 'xcodebuild']) {
    assert.ok(names.includes(required), `missing toolchain ${required}`);
  }
  const xcode = tools.find((t) => t.name === 'xcodebuild')!;
  if (process.platform !== 'darwin') {
    assert.equal(xcode.available, false);
    assert.match(xcode.reason ?? '', /macOS/);
  }
  for (const tool of tools) {
    if (tool.available) assert.ok(tool.executable);
    else assert.equal(tool.available, false);
  }
});

// Provisions validated APPOPS_* tool directories in tmp (outside HOME) so the
// planner emits real commands. These are directory/layout fixtures plus a fake
// version responders used only to test planner contracts — no real JDK/SDK/engine.
async function provisionTools(t: { after: (fn: () => void | Promise<void>) => void }, root: string): Promise<{
  restore: () => void;
  engineRoot: string;
}> {
  const gradleTools = join(root, 'tools/gradle');
  await mkdir(join(gradleTools, 'wrapper/dists/gradle-8.7-bin'), { recursive: true });
  await writeFile(join(gradleTools, 'wrapper/dists/gradle-8.7-bin/.ok'), '');
  await mkdir(join(gradleTools, 'dependency-cache'), { recursive: true });

  const godotData = join(root, 'tools/godot-data');
  await mkdir(join(godotData, 'export_templates/4.3.stable'), { recursive: true });

  const javaHome = join(root, 'tools/jdk');
  await mkdir(join(javaHome, 'bin'), { recursive: true });
  await writeFile(join(javaHome, 'bin/java'), '#!/bin/sh\nprintf \'openjdk version "21.0.1"\\n\'\n', { mode: 0o755 });
  await writeFile(join(javaHome, 'bin/javac'), '#!/bin/sh\nprintf \'javac 21.0.1\\n\'\n', { mode: 0o755 });
  await chmod(join(javaHome, 'bin/java'), 0o755);

  const sdk = join(root, 'tools/android-sdk');
  await mkdir(join(sdk, 'platforms/android-34'), { recursive: true });
  await mkdir(join(sdk, 'build-tools/34.0.0'), { recursive: true });
  await write(sdk, 'platforms/android-34/android.jar', 'planner fixture');
  await write(sdk, 'build-tools/34.0.0/lib/apksigner.jar', 'planner fixture');
  await write(sdk, 'build-tools/34.0.0/aapt2', '#!/bin/sh\nprintf \'Android Asset Packaging Tool (aapt) 2.19\\n\'\n');
  await chmod(join(sdk, 'build-tools/34.0.0/aapt2'), 0o755);
  await write(sdk, 'platform-tools/adb', '#!/bin/sh\nprintf \'Android Debug Bridge version 1.0.41\\n\'\n');
  await chmod(join(sdk, 'platform-tools/adb'), 0o755);

  // A minimal Unreal engine layout so unrealEngineRoot validates.
  const engineRoot = join(root, 'tools/UnrealEngine');
  await mkdir(join(engineRoot, 'Engine/Build/BatchFiles'), { recursive: true });
  await mkdir(join(engineRoot, 'Engine/Binaries/DotNET'), { recursive: true });
  await writeFile(join(engineRoot, 'Engine/Build/BatchFiles/RunUAT.sh'), '#!/bin/sh\nexit 0\n', { mode: 0o755 });
  await chmod(join(engineRoot, 'Engine/Build/BatchFiles/RunUAT.sh'), 0o755);

  const prior = {
    APPOPS_GRADLE_TOOLS_DIR: process.env.APPOPS_GRADLE_TOOLS_DIR,
    APPOPS_GODOT_DATA_DIR: process.env.APPOPS_GODOT_DATA_DIR,
    APPOPS_JAVA_HOME: process.env.APPOPS_JAVA_HOME,
    APPOPS_ANDROID_SDK_ROOT: process.env.APPOPS_ANDROID_SDK_ROOT,
  };
  process.env.APPOPS_GRADLE_TOOLS_DIR = gradleTools;
  process.env.APPOPS_GODOT_DATA_DIR = godotData;
  process.env.APPOPS_JAVA_HOME = javaHome;
  process.env.APPOPS_ANDROID_SDK_ROOT = sdk;
  const restore = () => {
    for (const [k, v] of Object.entries(prior)) {
      if (v === undefined) delete process.env[k];
      else process.env[k] = v;
    }
  };
  t.after(restore);
  return { restore, engineRoot };
}

test('createBuildPlan requires provisioned toolchains and fails closed with actionable findings when missing', async (t) => {
  const root = await tempDir(t, 'appops-plan-missing-');
  // Ensure APPOPS_* are unset for this test.
  const saved = {
    g: process.env.APPOPS_GRADLE_TOOLS_DIR, d: process.env.APPOPS_GODOT_DATA_DIR,
    j: process.env.APPOPS_JAVA_HOME, s: process.env.APPOPS_ANDROID_SDK_ROOT,
    jh: process.env.JAVA_HOME, ah: process.env.ANDROID_HOME, asr: process.env.ANDROID_SDK_ROOT,
  };
  delete process.env.APPOPS_GRADLE_TOOLS_DIR; delete process.env.APPOPS_GODOT_DATA_DIR;
  delete process.env.APPOPS_JAVA_HOME; delete process.env.APPOPS_ANDROID_SDK_ROOT;
  delete process.env.JAVA_HOME; delete process.env.ANDROID_HOME; delete process.env.ANDROID_SDK_ROOT;
  t.after(() => {
    for (const [k, v] of Object.entries({
      APPOPS_GRADLE_TOOLS_DIR: saved.g, APPOPS_GODOT_DATA_DIR: saved.d, APPOPS_JAVA_HOME: saved.j,
      APPOPS_ANDROID_SDK_ROOT: saved.s, JAVA_HOME: saved.jh, ANDROID_HOME: saved.ah, ANDROID_SDK_ROOT: saved.asr,
    })) { if (v === undefined) delete process.env[k]; else process.env[k] = v; }
  });

  const godot = join(root, 'godot');
  await write(godot, 'project.godot', godotProject);
  await write(godot, 'export_presets.cfg', godotPresets);
  const godotPlan = await createBuildPlan(await inspectProject(godot), { target: 'android', outputPath: join(root, 'out') });
  assert.equal(godotPlan.commands.length, 0);
  assert.ok(godotPlan.findings.some((f) => f.code === 'godot.missing_export_templates' && f.severity === 'error'));

  const android = join(root, 'android');
  await write(android, 'gradlew', '#!/bin/sh\nexit 0\n');
  await write(android, 'settings.gradle', "include ':app'\n");
  await write(android, 'app/build.gradle', 'android { defaultConfig { applicationId "com.h.a" } }\n');
  await write(android, 'app/src/main/AndroidManifest.xml', '<manifest package="com.h.a"></manifest>\n');
  const androidPlan = await createBuildPlan(await inspectProject(android), { target: 'android', outputPath: join(root, 'aab') });
  assert.equal(androidPlan.commands.length, 0);
  assert.ok(androidPlan.findings.some((f) => f.code === 'android.missing_gradle_cache'));
  assert.ok(androidPlan.findings.some((f) => f.code === 'android.missing_java' || f.code === 'android.missing_sdk'));
});

test('createBuildPlan uses official CLI argument arrays and mounts validated tool roots', async (t) => {
  const root = await tempDir(t, 'appops-plan-');
  await provisionTools(t, root);

  const godot = join(root, 'godot');
  await write(godot, 'project.godot', godotProject);
  await write(godot, 'export_presets.cfg', godotPresets);
  const inspection = await inspectProject(godot);
  const options: BuildOptions = { target: 'android', outputPath: join(root, 'out') };
  const plan = await createBuildPlan(inspection, options);
  assert.equal(plan.commands.length, 1);
  assert.deepEqual(plan.commands[0].args.slice(0, 3), ['--headless', '--path', inspection.rootPath]);
  assert.equal(plan.commands[0].args[3], '--export-release');
  assert.equal(plan.commands[0].args[4], 'Android');
  assert.ok(plan.commands[0].args[5].endsWith('.apk'));
  // Godot data dir surfaces to the runner via env for the per-run template link.
  assert.equal(plan.commands[0].env?.GODOT_TEMPLATES_SOURCE, process.env.APPOPS_GODOT_DATA_DIR);
  assert.ok(plan.commands[0].env?.XDG_DATA_HOME?.startsWith(join(root, 'out')));

  const noPreset = await createBuildPlan(inspection, { target: 'ios', outputPath: join(root, 'out-ios') });
  assert.equal(noPreset.commands.length, 0);
  assert.ok(noPreset.findings.some((f) => f.code === 'godot.missing_preset_for_target'));

  const android = join(root, 'android');
  await write(android, 'gradlew', '#!/bin/sh\nexit 0\n');
  await write(android, 'settings.gradle', "include ':app'\n");
  await write(android, 'app/build.gradle', 'android { defaultConfig { applicationId "com.harbor.android" } }\n');
  await write(android, 'app/src/main/AndroidManifest.xml', '<manifest package="com.harbor.android"></manifest>\n');
  const androidPlan = await createBuildPlan(await inspectProject(android), { target: 'android', outputPath: join(root, 'aab') });
  assert.equal(androidPlan.commands[0].executable, join(androidPlan.sourcePath, 'gradlew'));
  // Offline, no-daemon, task — the wrapper cannot download in the sandbox.
  assert.deepEqual(androidPlan.commands[0].args, ['--offline', '--no-daemon', 'app:bundleRelease']);
  assert.ok(androidPlan.expectedArtifacts[0].endsWith('.aab'));
  assert.equal(androidPlan.commands[0].env?.JAVA_HOME, process.env.APPOPS_JAVA_HOME);
  assert.equal(androidPlan.commands[0].env?.ANDROID_HOME, process.env.APPOPS_ANDROID_SDK_ROOT);
  assert.ok(androidPlan.commands[0].env?.GRADLE_USER_HOME?.startsWith(join(root, 'aab')));
  assert.ok(androidPlan.commands[0].env?.GRADLE_RO_DEP_CACHE?.includes('dependency-cache'));

  const unity = join(root, 'unity');
  await write(unity, 'ProjectSettings/ProjectVersion.txt', 'm_EditorVersion: 6000.0.23f1\n');
  await write(unity, 'ProjectSettings/ProjectSettings.asset', '  productName: U\napplicationIdentifier: com.u.app\n');
  await write(unity, 'Assets/A.txt', 'a');
  const linuxPlan = await createBuildPlan(await inspectProject(unity), { target: 'linux', outputPath: join(root, 'uout') });
  assert.ok(linuxPlan.commands[0].args.includes('-batchmode'));
  assert.ok(linuxPlan.commands[0].args.includes('-buildLinux64Player'));
  const androidUnity = await createBuildPlan(await inspectProject(unity), { target: 'android', outputPath: join(root, 'uand') });
  assert.equal(androidUnity.commands.length, 0);
  assert.ok(androidUnity.findings.some((f) => f.code === 'unity.missing_build_profile'));

  const unreal = join(root, 'unreal');
  await write(unreal, 'Game.uproject', '{"FileVersion":3,"EngineAssociation":"5.4"}\n');
  await write(unreal, 'Content/A.uasset', '');
  const uatPlan = await createBuildPlan(await inspectProject(unreal), {
    target: 'linux', outputPath: join(root, 'ue-out'), configuration: 'Shipping',
    engineExecutable: join(root, 'tools/UnrealEngine/Engine/Build/BatchFiles/RunUAT.sh'),
  });
  assert.equal(uatPlan.commands.length, 1);
  assert.equal(uatPlan.commands[0].args[0], 'BuildCookRun');
  assert.ok(uatPlan.commands[0].args.some((a) => a.startsWith('-platform=Linux')));
  assert.ok(uatPlan.commands[0].args.includes('-build'));
  assert.ok(uatPlan.commands[0].args.includes('-cook'));
  assert.ok(uatPlan.commands[0].args.includes('-package'));
  // Validated engine root is mounted for UAT's sibling AutomationTool/Binaries.
  assert.equal(uatPlan.commands[0].env?.UE_ENGINE_ROOT, join(root, 'tools/UnrealEngine'));
});

