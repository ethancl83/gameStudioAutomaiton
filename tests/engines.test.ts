test('inspects Godot, Unity, Unreal, Android and iOS from real project files', async (t) => {
  const root = await tempDir(t, 'appops-inspect-');

  const godot = join(root, 'godot');
  await write(godot, 'project.godot', godotProject);
  await write(godot, 'export_presets.cfg', godotPresets);
  const godotInfo = await inspectProject(godot);
  assert.equal(godotInfo.engine, 'godot');
  assert.equal(godotInfo.name, 'Harbor');
  assert.equal(godotInfo.engineVersion, '4.3');
  assert.equal(godotInfo.appIdentifier, 'com.harbor.game');
  assert.deepEqual(godotInfo.targets.sort(), ['android', 'linux']);
  assert.equal(godotInfo.rootPath, await realpath(godot));

  const unity = join(root, 'unity');
  await write(unity, 'ProjectSettings/ProjectVersion.txt', 'm_EditorVersion: 2022.3.21f1\n');
  await write(unity, 'ProjectSettings/ProjectSettings.asset', '  productName: Harbor Unity\napplicationIdentifier: com.harbor.unity\n');
  await write(unity, 'Assets/Main.unity', '');
  await write(unity, 'Packages/manifest.json', '{}\n');
  const unityInfo = await inspectProject(unity);
  assert.equal(unityInfo.engine, 'unity');
  assert.equal(unityInfo.engineVersion, '2022.3.21f1');
  assert.equal(unityInfo.appIdentifier, 'com.harbor.unity');

  const unreal = join(root, 'unreal');
  await write(unreal, 'Harbor.uproject', '{"FileVersion":3,"EngineAssociation":"5.4"}\n');
  await write(unreal, 'Config/DefaultEngine.ini', '[/Script/AndroidRuntimeSettings.AndroidRuntimeSettings]\nPackageName=com.harbor.unreal\n');
  await write(unreal, 'Content/Main.umap', '');
  const unrealInfo = await inspectProject(unreal);
  assert.equal(unrealInfo.engine, 'unreal');
  assert.equal(unrealInfo.engineVersion, '5.4');
  assert.equal(unrealInfo.appIdentifier, 'com.harbor.unreal');

  const android = join(root, 'android');
  await write(android, 'gradlew', '#!/bin/sh\necho SHOULD_NOT_RUN\nexit 99\n');
  await chmod(join(android, 'gradlew'), 0o755);
  await write(android, 'settings.gradle', "include ':app'\n");
  await write(android, 'app/build.gradle', 'android { defaultConfig { applicationId "com.harbor.android" } }\n');
  await write(android, 'app/src/main/AndroidManifest.xml', '<manifest package="com.harbor.android" android:label="Harbor"></manifest>\n');
  const androidInfo = await inspectProject(android);
  assert.equal(androidInfo.engine, 'android');
  assert.equal(androidInfo.appIdentifier, 'com.harbor.android');
  assert.deepEqual(androidInfo.targets, ['android']);

  const ios = join(root, 'ios');
  await write(ios, 'Harbor.xcodeproj/project.pbxproj', 'PRODUCT_BUNDLE_IDENTIFIER = com.harbor.ios;\n');
  await write(ios, 'Harbor.xcodeproj/xcshareddata/xcschemes/Harbor.xcscheme', '<Scheme></Scheme>\n');
  const iosInfo = await inspectProject(ios);
  assert.equal(iosInfo.engine, 'ios');
  assert.equal(iosInfo.appIdentifier, 'com.harbor.ios');
  if (process.platform !== 'darwin') {
    assert.ok(iosInfo.findings.some((f) => f.code === 'ios.requires_macos'));
  }
});

